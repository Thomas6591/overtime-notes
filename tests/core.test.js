const assert=require('node:assert/strict');const C=require('../app/src/main/assets/core');
const base={id:'a',date:'2026-10-21',start:'18:00',end:'20:30',nextDay:false,break:30,type:'工作日',note:''};
assert.equal(C.calculate(base).minutes,120);
assert.equal(C.calculate({...base,start:'23:00',end:'02:00',nextDay:true,break:20}).minutes,160);
assert.throws(()=>C.calculate({...base,start:'23:00',end:'02:00'}));
assert.throws(()=>C.calculate({...base,break:150}));
assert.throws(()=>C.calculate({...base,break:-1}));
assert.throws(()=>C.calculate({...base,break:1.5}));
assert.throws(()=>C.calculate({...base,date:'2026-02-30'}));
assert.equal(C.calculate({...base,date:'2024-02-29'}).minutes,120);
assert.throws(()=>C.calculate({...base,nextDay:true}));
assert.equal(C.calculate({...base,end:'18:00',nextDay:true,break:0}).minutes,1440);
assert.equal(C.overlap(base,{...base,start:'20:30',end:'21:00',break:0}),false);
assert.equal(C.overlap(base,{...base,start:'20:29',end:'21:00',break:0}),true);
assert.equal(C.overlap({...base,start:'23:00',end:'02:00',nextDay:true},{...base,date:'2026-10-22',start:'01:00',end:'03:00'}),true);
const stats=C.summarize([base,{...base,id:'b',start:'21:00',end:'22:00',break:0},{...base,id:'c',date:'2026-11-01'}],'2026-10');
assert.equal(stats.total,180);assert.equal(stats.days,1);assert.equal(stats.count,2);
assert.equal(C.summarize([{...base,date:'2026-10-31',start:'23:00',end:'01:00',nextDay:true,break:0}],'2026-10').total,120);
assert.equal(C.hours(60), '1');assert.equal(C.hours(600),'10');assert.equal(C.hours(0),'0');assert.equal(C.hours(95),'1.58');assert.equal(C.exact(95),'1小时35分');
console.log('PASS: 22 calculation, validation, overlap and aggregation assertions');
